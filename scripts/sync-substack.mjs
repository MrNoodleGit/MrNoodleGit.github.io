#!/usr/bin/env node
// Regenerates writing.md from the Substack RSS feed. Run on a schedule by
// .github/workflows/sync-substack.yml, or manually with:
//   node scripts/sync-substack.mjs

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const FEED_URL = "https://ramour.substack.com/feed";
const OUTPUT_PATH = fileURLToPath(new URL("../writing.md", import.meta.url));

function decodeEntities(str) {
  return str
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, "$1")
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, " ");
}

function stripTags(str) {
  return str.replace(/<[^>]+>/g, "").trim();
}

function extract(tag, block) {
  const match = block.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`));
  return match ? decodeEntities(match[1]).trim() : "";
}

function formatDate(pubDate) {
  const date = new Date(pubDate);
  if (isNaN(date)) return pubDate;
  return date.toLocaleDateString("en-US", {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });
}

async function fetchEssays() {
  const res = await fetch(FEED_URL);
  if (!res.ok) throw new Error(`Feed request failed: ${res.status} ${res.statusText}`);
  const xml = await res.text();

  const items = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map((m) => m[1]);

  return items
    .map((block) => ({
      title: extract("title", block),
      url: extract("link", block),
      pubDate: extract("pubDate", block),
      excerpt: stripTags(extract("description", block)),
    }))
    .filter((essay) => essay.title && essay.url)
    .sort((a, b) => new Date(b.pubDate) - new Date(a.pubDate));
}

function render(essays) {
  const header = `# Essays

<!--
  AUTO-GENERATED by .github/workflows/sync-substack.yml from
  ${FEED_URL} — do not edit by hand, changes will be overwritten on the
  next sync. To fix a title/date/excerpt, edit the Substack post itself.

  Read by js/writing-data.js: entries are separated by a line containing
  only "---"; "title:", "date:", and "url:" lines can appear in any
  order; any other line is the excerpt.
-->

`;

  const body = essays
    .map((essay) =>
      `title: ${essay.title}\ndate: ${formatDate(essay.pubDate)}\nurl: ${essay.url}\n${essay.excerpt}`.trim()
    )
    .join("\n\n---\n\n");

  return header + body + "\n";
}

const essays = await fetchEssays();
await writeFile(OUTPUT_PATH, render(essays));
console.log(`Wrote ${essays.length} essay(s) to writing.md`);
